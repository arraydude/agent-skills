#!/usr/bin/env python3
"""Compile a rule-based skill's AGENTS.md from its SKILL.md index and rules/.

Usage: scripts/build-agents-md.py skills/<skill> [--check]

The SKILL.md "Quick reference" section is the source of order: each
"### N. Category (IMPACT)" heading is a section and each "- `rule-id`" bullet
below it is a rule. Everything in SKILL.md between the H1 and "## Rule
categories" is copied in as the preamble.

--check exits non-zero, writing nothing, when the index and rules/ disagree or
when AGENTS.md is out of date.
"""
import re
import sys
from pathlib import Path


def slug(text: str) -> str:
    text = re.sub(r"[^\w\- ]", "", text.lower())
    return text.replace(" ", "-")


def frontmatter(text: str) -> tuple[dict, str]:
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}, text
    fields = {}
    for line in match.group(1).splitlines():
        if ": " in line:
            key, value = line.split(": ", 1)
            fields[key.strip()] = value.strip().strip('"')
    return fields, text[match.end():]


def parse_index(skill_md: str) -> list[tuple[str, str, list[str]]]:
    body = re.split(r"^## Quick reference\s*$", skill_md, flags=re.M | re.I)[1]
    body = re.split(r"^## ", body, flags=re.M)[0]
    sections = []
    for block in re.split(r"^### ", body, flags=re.M)[1:]:
        heading = block.splitlines()[0]
        match = re.match(r"\d+\.\s*(.+?)\s*\((\w+)\)\s*$", heading)
        if not match:
            sys.exit(f"Unparseable category heading: {heading!r}")
        ids = re.findall(r"^- `([a-z0-9-]+)`", block, flags=re.M)
        sections.append((match.group(1), match.group(2), ids))
    return sections


def build(skill: Path) -> str:
    skill_md = (skill / "SKILL.md").read_text()
    meta, body = frontmatter(skill_md)
    title = re.search(r"^# (.+)$", body, flags=re.M).group(1)
    preamble = body.split(f"# {title}", 1)[1]
    preamble = re.split(r"^## Rule categories", preamble, flags=re.M | re.I)[0].strip()
    version = re.search(r'version:\s*"?([\d.]+)', skill_md)

    sections = parse_index(skill_md)
    indexed = [rid for _, _, ids in sections for rid in ids]
    files = sorted(p.stem for p in (skill / "rules").glob("*.md"))
    dupes = sorted({r for r in indexed if indexed.count(r) > 1})
    missing = sorted(set(indexed) - set(files))
    unindexed = sorted(set(files) - set(indexed))
    if dupes or missing or unindexed:
        sys.exit(
            "Index and rules/ disagree:\n"
            f"  indexed twice: {dupes}\n  no rule file: {missing}\n  not indexed: {unindexed}"
        )

    toc, out = [], []
    for n, (category, impact, ids) in enumerate(sections, 1):
        head = f"{n}. {category}"
        toc.append(f"{n}. [{category}](#{slug(head)}) — **{impact}**")
        out.append(f"## {head}\n\n**Impact: {impact}**\n")
        for m, rid in enumerate(ids, 1):
            fields, rule = frontmatter((skill / "rules" / f"{rid}.md").read_text())
            rule = re.sub(r"\A\s*## .*\n+", "", rule).rstrip()
            rule_title = fields.get("title", rid)
            sub = f"{n}.{m} {rule_title}"
            toc.append(f"   - {n}.{m} [{rule_title}](#{slug(sub)})")
            badges = [f"**Impact: {fields.get('impact', '?')} ({fields.get('impactDescription', '')})**"]
            if fields.get("versions"):
                badges.append(f"**Versions:** {fields['versions']}")
            if fields.get("since"):
                badges.append(f"**Since:** {fields['since']}")
            out.append(f"### {sub}\n\n{' · '.join(badges)}\n\n{rule}\n")

    header = [
        f"<!-- Generated by scripts/build-agents-md.py from SKILL.md and rules/. Edit those, then rebuild. -->",
        f"# {title}",
        "",
        f"**Version {version.group(1)}**" if version else "",
        "",
        preamble,
        "",
        "## Table of Contents",
        "",
        *toc,
        "",
        "---",
        "",
    ]
    return "\n".join(header) + "\n".join(out)


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    skill = Path(args[0])
    compiled = build(skill)
    target = skill / "AGENTS.md"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != compiled:
            sys.exit(f"{target} is out of date: run scripts/build-agents-md.py {skill}")
        print(f"{target} is up to date")
        return
    target.write_text(compiled)
    print(f"Wrote {target}")


if __name__ == "__main__":
    main()
